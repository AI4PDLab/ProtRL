import argparse
import os
import sys
import pandas as pd
import numpy as np

# Add parent directory to path to import utils
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

def main():
    """
    Calculates the reward for the GRPO_ProtPMNN experiment.
    Reward is defined as the negative ProteinMPNN score (maximizing -Score <=> minimizing NLL).
    Reads pre-calculated ProteinMPNN scores from .npz files generated by run_mpnn_batch.py.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--iteration_num", type=int, required=True, help="Current iteration number")
    parser.add_argument("--label", type=str, required=True, help="Label for the experiment (unused but kept for compatibility)")
    parser.add_argument("--output_dir", type=str, default=".", help="Directory containing logs and results")
    args = parser.parse_args()

    logs_file = os.path.join(args.output_dir, "logs.csv")
    
    # 1. Validation: Check if logs file exists
    if not os.path.exists(logs_file):
        print(f"Error: Logs file not found at {logs_file}")
        return

    # 2. Validation: Check if ProteinMPNN output directory exists
    mpnn_output_dir = os.path.join(args.output_dir, "ProteinMPNN_scores")
    if not os.path.exists(mpnn_output_dir):
        print(f"Error: ProteinMPNN output directory not found at {mpnn_output_dir}")
        print("Ensure 'run_mpnn_batch.py' was executed successfully.")
        return

    try:
        df = pd.read_csv(logs_file)
    except Exception as e:
        print(f"Error reading logs file: {e}")
        return
    
    # Filter for current iteration to process only relevant rows
    mask = df['iteration_num'] == args.iteration_num
    
    if not mask.any():
        print(f"Warning: No rows found for iteration {args.iteration_num}")
        return

    print(f"Processing rewards for iteration {args.iteration_num}...")

    # 3. Read ProteinMPNN Scores
    mpnn_scores = {}
    
    # Read all .npz files in the output directory
    # Each file corresponds to a sequence/structure
    for f in os.listdir(mpnn_output_dir):
        if f.endswith(".npz"):
            try:
                # ProteinMPNN output format assumption:
                # .npz file containing 'score' field (mean negative log prob)
                file_path = os.path.join(mpnn_output_dir, f)
                data = np.load(file_path)
                
                # Filename is typically the sequence name
                name = f.replace(".npz", "")
                
                if 'score' in data:
                    mpnn_scores[name] = float(data['score'])
                else:
                    print(f"Warning: 'score' key missing in {f}")
            except Exception as e:
                print(f"Warning: Failed to read {f}: {e}")

    # 4. Update DataFrame
    # Iterate over the filtered rows and assign rewards
    updates_count = 0
    missing_scores_count = 0
    
    for index, row in df[mask].iterrows():
        name = row['name']
        
        if name in mpnn_scores:
            score = mpnn_scores[name]
            
            # Log the raw score
            df.at[index, 'proteinmpnn_score'] = score
            
            # Reward Definition:
            # ProteinMPNN score is usually NLL (loss), so lower is better.
            # RL maximizes reward, so we use -1 * score.
            df.at[index, 'reward'] = -1.0 * score
            updates_count += 1
        else:
            print(f"Warning: No ProteinMPNN score found for sequence '{name}'")
            # Assign a penalty or potentially skip training on this example
            df.at[index, 'reward'] = -999.0 
            missing_scores_count += 1

    # 5. Save Results
    try:
        df.to_csv(logs_file, index=False)
        print(f"Successfully updated rewards for {updates_count} sequences.")
        if missing_scores_count > 0:
            print(f"Warning: {missing_scores_count} sequences were missing scores.")
            
    except Exception as e:
        print(f"Error saving updated logs file: {e}")

if __name__ == "__main__":
    main()
